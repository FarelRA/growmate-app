# ─── Emit ───

def slug(s):
    s = s.lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")


def ts_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build():
    entries = []
    seen = set()
    idx = 0
    for (base_key, name, species, cat, suit, diff, loc, wT, lT, fertThr,
         fertCad, pestCad, note, img_idx, life_ov, varieties) in CROPS:
        # "both" in the table means pod + field; schema only allows the literals.
        suit = ["pod", "field"] if suit == ["both"] else list(suit)
        soil, light, temp, air, water = CAT[cat][0], CAT[cat][1], CAT[cat][2], CAT[cat][3], CAT[cat][4]
        life = life_ov or CAT[cat][10]
        for vi, (suffix, trait) in enumerate(varieties):
            key = base_key if not suffix else f"{base_key}-{slug(suffix)}"
            assert key not in seen, f"duplicate key {key}"
            seen.add(key)
            full_name = name if not suffix else f"{name} {suffix}"
            img_hash = BASE_IMAGE[base_key]
            j = (idx * 7) % 5 - 2
            j2 = (idx * 11) % 5 - 2
            if suit == ["field"]:
                ctx = ("Tahan kering dan cocok ditanam di lahan sawah/tegal pada masa transisi akhir kemarau "
                       "menuju Musim Tanam Pertama.")
            elif suit == ["pod"]:
                ctx = "Cocok untuk budidaya hidroponik dan GrowMate Pods."
            elif wT <= 55:
                ctx = ("Tahan kering untuk Musim Tanam Pertama; adaptif pula untuk hidroponik.")
            else:
                ctx = "Adaptif untuk hidroponik maupun lahan pekarangan."
            desc = f"{full_name} ({species}). {trait} {ctx}"
            sd, gd, sgd, vgd, frd, msd = life
            suit_ts = ", ".join(f'"{s}"' for s in suit)
            entries.append("  {\n"
                f'    key: "{key}",\n'
                f"    name: {ts_str(full_name)},\n"
                f"    species: {ts_str(species)},\n"
                f"    description: {ts_str(desc)},\n"
                f"    location: {ts_str(loc)},\n"
                f'    category: "{cat}",\n'
                f'    difficulty: "{diff}",\n'
                f"    wateringThreshold: {wT},\n"
                f"    lightingThreshold: {lT},\n"
                f"    fertilizingThreshold: {fertThr},\n"
                f"    fertilizerCadenceDays: {fertCad},\n"
                f"    pesticideCadenceDays: {pestCad},\n"
                f"    nutrientNotes: {ts_str(note)},\n"
                f"    suitableFor: [{suit_ts}],\n"
                "    sensorProfile: {\n"
                f"      soil: {{ min: {soil[0] + j}, max: {soil[1] + j} }},\n"
                f"      light: {{ min: {light[0] + j}, max: {light[1] + j} }},\n"
                f"      temperature: {{ min: {temp[0]}, max: {temp[1]} }},\n"
                f"      air: {{ min: {air[0] + j2}, max: {air[1] + j2} }},\n"
                f"      water: {{ min: {water[0] + j}, max: {water[1] + j} }},\n"
                "    },\n"
                "    lifecycleProfile: {\n"
                f"      seedDormancyDays: {sd},\n"
                f"      germinationDays: {gd},\n"
                f"      seedlingDevelopmentDays: {sgd},\n"
                f"      vegetativeGrowthDays: {vgd},\n"
                f"      floweringReproductionDays: {frd},\n"
                f"      maturitySenescenceDays: {msd},\n"
                "    },\n"
                f'    image: {{ hash: "{img_hash}" }},\n'
                "  },")
            idx += 1
    return entries, seen


def main():
    entries, seen = build()
    print(f"varieties: {len(entries)}")
    assert len(entries) >= 500, f"only {len(entries)}, need >= 500"
    head = ("// Seed dataset — generated by scripts/generate-plant-catalog.py. Do not edit\n"
            "// manually; extend the CROPS table in the generator and re-run.\n"
            "// Image bytes live in public/seed-images/<hash>/; entries carry only hashes.\n\n"
            "import type { PlantSeedData } from './types'\n\n"
            "const seedData: PlantSeedData[] = [\n")
    tail = "]\n\nexport default seedData\n"
    OUT.write_text(head + "\n".join(entries) + "\n" + tail)
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024}KB)")


if __name__ == "__main__":
    main()
